#pragma once
// ============================================================================
//  EcsVerify.hpp — 「反应式/信任式快路的**验证 oracle**」总开关(默认 0)。
//
//  ── 为什么是一个跨层的独立开关 ────────────────────────────────────────────
//
//  本仓有一类共同的性能改造:把「每帧重新发现变化」换成「信任某个更便宜的
//  判据」——
//
//    · 抽取节点(ecs/render):全扫比对 → 信号驱动的变更集;
//    · 变换系统(ecs/core)  :逐实体值比较 → 信任 `Local::dirty` + 信号。
//
//  它们共享**同一种失败模式**:判据漏了一种变化,于是那类更新永远不发生 ——
//  而它**不报错**。构建全绿、测试全过、进程干净退出,症状只是「某个东西不动
//  了/不渲染」(CLAUDE.md 的 ECS 观察者一节把这条列为铁律)。
//
//  处方也是同一个:**把被替换掉的那段慢逻辑原地保留,降级成 oracle** ——
//  快路跑完之后再用慢逻辑跑一遍,如果它还能找出活干,就说明快路漏了。
//  判据干净:oracle 找不到活干 ⟺ 快路没漏。
//
//  于是「无需纪律」这个属性并没有消失,它从**每帧的运行时开销**变成了
//  **debug 构型下的一条断言**。
//
//  ⚠️ 开关只有这一份。此前 render 层自己定义过一份同名宏,两处各有默认值 ——
//     有人翻一个不翻另一个就会静默不一致(而不一致的那一半正好是安全网)。
//
//  打开方式:给相关目标加 `-DLUX_ECS_EXTRACTION_VERIFY=1` 重编。
//  代价:多跑一遍原来的慢逻辑(抽取节点是多一遍全扫;变换是多一遍值比较)。
// ============================================================================

#ifndef LUX_ECS_EXTRACTION_VERIFY
#  define LUX_ECS_EXTRACTION_VERIFY 0
#endif
