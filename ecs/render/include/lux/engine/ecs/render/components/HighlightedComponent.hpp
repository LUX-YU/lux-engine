// ============================================================================
//  HighlightedComponent.hpp — 「这个实体现在是高亮的」。一个纯标签组件。
//
//  ── 它取代了什么 ──────────────────────────────────────────────────────────
//
//  此前高亮是**宿主推给渲染系统的一坨状态**：编辑器每帧算出一个
//  `unordered_set<entity_id>`，调 `RenderSystem::setHighlighted(std::move(set))`，
//  渲染上下文存着它，网格子系统再 `ctx.isHighlighted(e)` 查。
//
//  三处不对：
//   ① 那是一条具名 setter —— 与 `setSkinningOps` 一类同源，「引擎层要认识
//      编辑器的选中概念」。渲染系统不该有一个专为某个宿主的某个功能开的入口。
//   ② 那份集合是**世界状态的镜像**，而镜像必然会漂：实体销毁了、集合里还留着，
//      靠每帧全量重推来掩盖。
//   ③ 高亮本来就是「实体的一个属性」——ECS 里那叫组件。
//
//  现在：谁想高亮谁就给实体挂上这个标签，网格子系统 `all_of` 一下。渲染侧不再
//  认识「选中」，编辑器也不再需要够得着 `RenderSystem`。
//
//  故意**不是反射组件**：它是运行期的瞬时状态，不存盘、不该出现在属性面板。
//
//  ⚠️ 挂在**哪些**实体上是调用方的事。编辑器的规矩是「整个物体高亮」——选中的
//     根 + 它子树里每个网格实体（W1-B 把点选提升到根，而根自己可能没有网格）。
//     那条规矩属于编辑器，不属于这里。
// ============================================================================

